/**
 * wedding-invitation — "Wedding Invitation" (Classic · the Gulabi Jharokha) on
 * the Valentine engine + the wedding kit. Paths resolve against
 * `ValentineDayData` (client app/(templates)/_valentine/types.ts); extras keys
 * are defined in server/src/config/valentineDays.ts ("wedding-invitation").
 *
 * The engine's two names are the COUPLE: recipientName = the bride,
 * senderName = the groom. `letter` is the English invitation guests read
 * first, `extras.hindiMessage` the Hindi one beside it, `endLine` the closing
 * line at the very end.
 *
 * The editor usually reaches this through six guided questions (client
 * studio/WeddingGuided.tsx): the answers arrive as one plain description
 * ("Aanya (the bride) and Vihaan (the groom) are getting married. The wedding
 * ceremony is on Saturday, 12 December 2026 (2026-12-12) at 7:30 pm at …"),
 * plus hints {tone, language, occasion: "wedding"}. The client writes the
 * typed names, date, time and contact back over the model's, so the model's
 * job is the prose and the function rows.
 *
 * The editor opens on a demo wedding with five functions (rows 0–4), two story
 * chapters and two contacts, so those indices always exist. The client drops
 * demo rows the model left untouched, so a short description gives a short page.
 *
 * Budget (field cap 40): 2 names, the wedding date, the invitation in English
 * and Hindi, both families, five functions × (name, date, time, venue, dress
 * code), two story chapters × (title, line), one contact person (name,
 * phone) and the closing line = 39. The contact's relation is left to the
 * sender: the model invented one ('Friend') whenever the description gave a
 * bare name and number, whatever the guide said. Not declared: theme / music /
 * photos (visual choices), map links, livestream and UPI (the model would
 * invent them; a UPI id is money), event ids (the RSVP key: generated by the
 * form), dress colours (the client derives a swatch from the dress-code words),
 * the start time (the client takes it from the main function's row or the
 * typed answer), RSVP settings (the sender's decisions).
 */

const TONE =
  " Write in the register the description asks for (traditional, royal, warm & modern, faith-filled, fun); without a cue, warm and graceful. Never cheesy, no exclamation-mark spam, no emoji. Write in English unless the description is written in Hindi or Hinglish; never mix scripts inside one field.";

const FUNCTION_ROWS = 5;

/**
 * The model has no calendar, and on a bare "12 Dec" it reaches for its training
 * year. A wedding is always ahead, so the guides carry the date the server
 * booted (a deploy restarts it, so it never drifts by more than days).
 */
const TODAY = new Date().toISOString().slice(0, 10);
const NO_YEAR = `Write a date only when the description names the day of the month as a number ('12 December', '12/12', 'the 10th'); with only a month or a season, return null. A wedding is always in the future: when the description gives a day and a month but no year, use the first such date after ${TODAY}.`;

const functionFields: AiFillField[] = Array.from({ length: FUNCTION_ROWS }, (_, i) => [
  {
    path: `extras.events[${i}].title`,
    label: `Function ${i + 1} — name`,
    kind: "text" as const,
    max: 40,
    guide:
      i === 0
        ? "The FIRST function of the wedding in date order, by its usual name: Roka, Engagement, Tilak, Haldi, Mehendi, Sangeet, Baraat, 'Wedding (Pheras)', Nikah, Anand Karaj, Muhurtham, 'Church Wedding', 'Registry Wedding', Cocktail, Reception… Rows run in date order, one function per row. List ONLY functions the description mentions; when it mentions none, write just the wedding ceremony itself in this row ('Wedding (Pheras)' for a Hindu North Indian wedding, 'Muhurtham' for a Tamil wedding, 'Wedding Ceremony' for a church wedding, 'Registry Wedding' for a court marriage). Under 30 characters."
        : `Function ${i + 1} in date order, by its usual name (see function 1). Only a function the description mentions. If the wedding has fewer than ${i + 1} functions, return null for this row and every field of it — never invent one. Under 30 characters.`,
  },
  {
    path: `extras.events[${i}].date`,
    label: `Function ${i + 1} — date`,
    kind: "date" as const,
    guide: `The date of function ${i + 1} as YYYY-MM-DD. When the description gives only the day ('Haldi on the 10th') take the month and year from the wedding date it states; the wedding ceremony row takes the wedding date. ${NO_YEAR} Null when the row is empty or the date is unknown.`,
  },
  {
    path: `extras.events[${i}].time`,
    label: `Function ${i + 1} — start time`,
    kind: "text" as const,
    max: 5,
    guide: `The start time of function ${i + 1} in 24-hour HH:mm ('19:30' for 7:30 pm, '07:00' for 7 am). Only a time the description states for this function; otherwise null.`,
    example: "19:30",
  },
  {
    path: `extras.events[${i}].venue`,
    label: `Function ${i + 1} — venue`,
    kind: "text" as const,
    max: 80,
    guide: `Where function ${i + 1} happens: the venue name and city from the description ('The Leela Palace, Udaipur'; 'Bride's home, Kanpur'), in English words and Latin script even when the description is in Hindi or Hinglish (a family home becomes 'Family home, Lucknow'). When a function has no venue of its own, write the city the description gives for the wedding. Null when the description names no place at all; never invent a venue.`,
  },
  {
    path: `extras.events[${i}].dressCode`,
    label: `Function ${i + 1} — dress code`,
    kind: "text" as const,
    max: 60,
    guide: `A short dress-code line for function ${i + 1}, guests read it under the function: the description's own when it gives one, else the custom for that function (Haldi 'Shades of yellow', Mehendi 'Greens and bright florals', Sangeet 'Indo-western glam', Hindu wedding 'Traditional festive', church wedding 'Formal, pastels', Reception or Cocktail 'Pastels and ivory' / 'Cocktail chic'). Mention a colour when it is customary — the page draws a swatch from it. Under 40 characters. Null for an empty row.`,
    example: "Shades of yellow",
  },
]).flat();

const storyFields: AiFillField[] = [0, 1].flatMap((i) => [
  {
    path: `extras.story[${i}].title`,
    label: `Our story ${i + 1} — title`,
    kind: "text" as const,
    max: 60,
    guide: `Chapter ${i + 1} of the couple's story (${["how they met", "a moment between meeting and the wedding: the proposal, the roka, the families meeting"][i]}), as a short evocative title ('A borrowed umbrella', 'A ring by the lake'). First find the description's own sentence about that moment (where or how they met; how the proposal happened) and build the title from its facts. When you cannot point to such a sentence, the chapter stays empty: return null for this title and its line. A function of the wedding itself (engagement ceremony, registration) is not a story chapter. No emoji. Under 40 characters.`,
  },
  {
    path: `extras.story[${i}].line`,
    label: `Our story ${i + 1} — what happened`,
    kind: "text" as const,
    max: 240,
    guide:
      `One or two sentences for chapter ${i + 1}, told about the couple in the third person ('They met…', 'He asked…'), with one specific detail from the description (the place, the year). Never invent events, places or years, and never restate a function's date. Null when the title is null. Under 200 characters.` +
      TONE,
  },
]);

